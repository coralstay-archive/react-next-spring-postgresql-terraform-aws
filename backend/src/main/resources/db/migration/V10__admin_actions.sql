-- 관리자 감사 로그 (TASK-12). 모든 관리 쓰기(정지·해제, 글 숨김·해제·복구, 카테고리 생성·수정·삭제)를 같은 트랜잭션에서 한 행씩 남긴다.
-- target_id 는 대상 행이 지워져도(카테고리 삭제) 남아야 하므로 FK 를 걸지 않는다.
CREATE TABLE admin_actions (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	admin_id     BIGINT       NOT NULL REFERENCES users (id),
	action       VARCHAR(40)  NOT NULL,
	target_type  VARCHAR(20)  NOT NULL,
	target_id    BIGINT       NOT NULL,
	reason       VARCHAR(500),
	created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT admin_actions_target_type_ck CHECK (target_type IN ('USER', 'POST', 'CATEGORY'))
);
-- 최근순 목록(GET /api/admin/actions)
CREATE INDEX admin_actions_created_ix ON admin_actions (created_at DESC, id DESC);
-- 대상별 이력
CREATE INDEX admin_actions_target_ix ON admin_actions (target_type, target_id);
