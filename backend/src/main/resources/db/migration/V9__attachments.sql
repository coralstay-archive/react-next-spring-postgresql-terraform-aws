-- 이미지 첨부 (TASK-11). 객체는 S3(로컬 MinIO)에 있고 여기에는 메타데이터만 둔다.
-- presign 때 PENDING 으로 만들고, 업로드 후 confirm(HeadObject 검증)에서 CONFIRMED 로 바꾼다. 글에는 CONFIRMED 만 붙는다.
-- 24시간 넘게 PENDING 인 행은 앱 스케줄러가 지우고, S3 객체는 status=pending 태그 lifecycle(1일)이 지운다.
CREATE TABLE attachments (
	id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	owner_id      BIGINT       NOT NULL REFERENCES users (id),
	post_id       BIGINT       REFERENCES posts (id) ON DELETE SET NULL,
	s3_key        VARCHAR(300) NOT NULL,
	content_type  VARCHAR(50)  NOT NULL,
	size          BIGINT       NOT NULL,
	status        VARCHAR(20)  NOT NULL,
	created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
	confirmed_at  TIMESTAMPTZ,
	CONSTRAINT attachments_s3_key_uq UNIQUE (s3_key),
	-- B1: image/png·jpeg·webp·gif, 5MB 이하
	CONSTRAINT attachments_content_type_ck CHECK (content_type IN ('image/png', 'image/jpeg', 'image/webp', 'image/gif')),
	CONSTRAINT attachments_size_ck CHECK (size > 0 AND size <= 5242880),
	CONSTRAINT attachments_status_ck CHECK (status IN ('PENDING', 'CONFIRMED')),
	CONSTRAINT attachments_confirmed_at_ck CHECK ((status = 'CONFIRMED') = (confirmed_at IS NOT NULL)),
	-- 글에는 확정된 첨부만 붙는다
	CONSTRAINT attachments_post_confirmed_ck CHECK (post_id IS NULL OR status = 'CONFIRMED')
);
CREATE INDEX attachments_owner_id_ix ON attachments (owner_id);
CREATE INDEX attachments_post_id_ix ON attachments (post_id) WHERE post_id IS NOT NULL;
-- 미확정 정리 스케줄러: created_at 이 오래된 PENDING
CREATE INDEX attachments_pending_created_ix ON attachments (created_at) WHERE status = 'PENDING';
