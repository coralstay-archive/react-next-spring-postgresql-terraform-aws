-- 게시판 (TASK-8): 카테고리·글·태그.
-- 조회수·좋아요(view_count, like_count)는 TASK-9, 검색(search_tsv)은 TASK-10 이 컬럼을 더한다.

CREATE TABLE categories (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	slug        VARCHAR(40)  NOT NULL,
	name        VARCHAR(50)  NOT NULL,
	sort_order  INT          NOT NULL DEFAULT 0,
	-- true 면 ADMIN 만 이 카테고리에 글을 쓰거나 글을 옮길 수 있다(예: 공지)
	admin_only  BOOLEAN      NOT NULL DEFAULT false,
	created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT categories_slug_uk UNIQUE (slug)
);

INSERT INTO categories (slug, name, sort_order, admin_only) VALUES
	('notice', '공지', 0, true),
	('free', '자유게시판', 10, false);

CREATE TABLE posts (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	author_id    BIGINT        NOT NULL REFERENCES users (id),
	category_id  BIGINT        REFERENCES categories (id) ON DELETE SET NULL,
	title        VARCHAR(100)  NOT NULL,
	content      TEXT          NOT NULL,
	created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
	updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
	-- soft delete (작성자·ADMIN 삭제)
	deleted_at   TIMESTAMPTZ,
	-- 관리자 숨김 (TASK-12)
	hidden_at    TIMESTAMPTZ
);

-- 목록(최신순): 보이는 글만 담는 부분 인덱스. 정렬 키는 (created_at DESC, id DESC).
CREATE INDEX posts_visible_latest_ix ON posts (created_at DESC, id DESC)
	WHERE deleted_at IS NULL AND hidden_at IS NULL;
CREATE INDEX posts_category_visible_latest_ix ON posts (category_id, created_at DESC, id DESC)
	WHERE deleted_at IS NULL AND hidden_at IS NULL;
CREATE INDEX posts_author_id_ix ON posts (author_id);

CREATE TABLE tags (
	id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	-- 정규화된 이름(소문자, trim, 공백 1칸, 최대 30자)
	name  VARCHAR(30) NOT NULL,
	CONSTRAINT tags_name_uk UNIQUE (name)
);

CREATE TABLE post_tags (
	post_id  BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
	tag_id   BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
	PRIMARY KEY (post_id, tag_id)
);
-- 태그 필터·태그별 글 수
CREATE INDEX post_tags_tag_id_ix ON post_tags (tag_id, post_id);
