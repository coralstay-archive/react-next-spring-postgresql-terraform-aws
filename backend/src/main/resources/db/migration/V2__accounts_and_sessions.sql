-- 통합 계정 모델 (decision-4): 계정 1개 + 로그인 수단 N개.
-- users.email/phone 은 표시·연락용이고 로그인 키가 아니다. 로그인 키는 user_identities(provider, subject)다.

CREATE TABLE users (
	id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nickname    VARCHAR(50)  NOT NULL,
	email       VARCHAR(320),
	phone       VARCHAR(32),
	role        VARCHAR(20)  NOT NULL DEFAULT 'USER',
	status      VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
	created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT users_role_chk   CHECK (role IN ('USER', 'ADMIN')),
	CONSTRAINT users_status_chk CHECK (status IN ('ACTIVE', 'SUSPENDED'))
);

CREATE TABLE user_identities (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	provider   VARCHAR(20)  NOT NULL,
	subject    VARCHAR(255) NOT NULL,
	email      VARCHAR(320),
	linked_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT user_identities_provider_subject_uk UNIQUE (provider, subject),
	CONSTRAINT user_identities_provider_chk
		CHECK (provider IN ('LOCAL', 'GOOGLE', 'GITHUB', 'NAVER', 'KAKAO', 'COGNITO', 'PHONE'))
);
CREATE INDEX user_identities_user_id_ix ON user_identities (user_id);

-- 비밀번호는 LOCAL identity 에만 둔다.
CREATE TABLE local_credentials (
	identity_id    BIGINT       PRIMARY KEY REFERENCES user_identities (id) ON DELETE CASCADE,
	password_hash  VARCHAR(255) NOT NULL,
	updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- JWT refresh 로테이션 + 재사용 감지 (decision-5). 원문 토큰은 저장하지 않고 해시만 둔다.
CREATE TABLE refresh_tokens (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
	token_hash   VARCHAR(128) NOT NULL,
	family_id    UUID         NOT NULL,
	expires_at   TIMESTAMPTZ  NOT NULL,
	revoked_at   TIMESTAMPTZ,
	replaced_by  BIGINT       REFERENCES refresh_tokens (id),
	created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
	CONSTRAINT refresh_tokens_token_hash_uk UNIQUE (token_hash)
);
CREATE INDEX refresh_tokens_user_id_ix ON refresh_tokens (user_id);
CREATE INDEX refresh_tokens_family_id_ix ON refresh_tokens (family_id);

-- Spring Session JDBC 공식 PostgreSQL 스키마 (spring-session-jdbc 4.1.1 schema-postgresql.sql 그대로).
-- spring.session.jdbc.initialize-schema=never 로 두고 Flyway 가 관리한다.
CREATE TABLE SPRING_SESSION (
	PRIMARY_ID CHAR(36) NOT NULL,
	SESSION_ID CHAR(36) NOT NULL,
	CREATION_TIME BIGINT NOT NULL,
	LAST_ACCESS_TIME BIGINT NOT NULL,
	MAX_INACTIVE_INTERVAL INT NOT NULL,
	EXPIRY_TIME BIGINT NOT NULL,
	PRINCIPAL_NAME VARCHAR(100),
	CONSTRAINT SPRING_SESSION_PK PRIMARY KEY (PRIMARY_ID)
);

CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);

CREATE TABLE SPRING_SESSION_ATTRIBUTES (
	SESSION_PRIMARY_ID CHAR(36) NOT NULL,
	ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
	ATTRIBUTE_BYTES BYTEA NOT NULL,
	CONSTRAINT SPRING_SESSION_ATTRIBUTES_PK PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
	CONSTRAINT SPRING_SESSION_ATTRIBUTES_FK FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE
);
