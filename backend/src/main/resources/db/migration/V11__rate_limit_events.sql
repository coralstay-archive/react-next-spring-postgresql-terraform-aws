-- 공용 레이트리밋 이벤트 (TASK-22, doc-2 BE-13·31·34). 한도마다(bucket) 키별로 이벤트 시각을 쌓고, 슬라이딩 창 안의 개수를 센다 →
-- DB 하나를 보므로 인스턴스가 여러 개여도 같은 한도다. "세고 → 넣기"는 (bucket, key) 별 트랜잭션 advisory lock 으로 직렬화한다.
-- key_hash: SHA-256(bucket + 키) hex. 이메일·IP·사용자 id 원문은 남기지 않는다.
-- 정리: 가장 긴 창(1시간)보다 오래된 행은 쓸모가 없다 — 정리 잡은 TASK-27.
CREATE TABLE rate_limit_events (
	id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	bucket       VARCHAR(40)  NOT NULL,
	key_hash     CHAR(64)     NOT NULL,
	occurred_at  TIMESTAMPTZ  NOT NULL
);
CREATE INDEX rate_limit_events_bucket_key_ix ON rate_limit_events (bucket, key_hash, occurred_at);
-- 정리 잡(TASK-27)이 occurred_at 으로 오래된 행을 지운다
CREATE INDEX rate_limit_events_occurred_ix ON rate_limit_events (occurred_at);
